  /**
   * Hydrates any <i data-lucide="..."></i> elements in the DOM.
   */
  window.hydrateErpIcons = function (root = document) {
    const nodes = root.querySelectorAll('[data-lucide]');
    nodes.forEach((node) => {
      const name = node.getAttribute('data-lucide');
      const size = parseInt(node.getAttribute('data-size') || '18', 10);
      const cls = node.getAttribute('class') || '';
      const span = document.createElement('span');
      span.innerHTML = window.erpIcon(name, size, cls);
      if (span.firstElementChild) {
        node.replaceWith(span.firstElementChild);
      }
    });
  };

